function classifyFisheries(name) {
  const bare = name.startsWith(TICK) ? name.slice(TICK.length) : name;
  if (FISH_KEEP.has(bare)) return { keep: true, note: 'genuine fisheries' };
  for (const re of FISH_KEEP_RE) if (re.test(bare)) return { keep: true, note: 'genuine fisheries (re)' };
  // fish/aquatic taxonomy suffixes ΓåÆ keep (Acropomatidae, Acanthuriformes, Achelata, Aeglidae...)
  if (/(?:iformes|opterygii|oidea|idae|acea|ognatha|morphi|dontia|thyes|branchii|stomi|pelagi|caridea|chelata|eglidae|nephropida|astacidea|paguroidea|pleocyemata|dendrobranchiata)$/i.test(bare)) return { keep: true, note: 'aquatic taxa' };
  if (OVERRIDES[bare]) return { dest: OVERRIDES[bare], note: 'override' };
  for (const r of FISH_RULES) if (r.re.test(bare)) return r;
  return { dest: FISH_AUTO.dest, note: 'auto-assign fallback' };
}

function classifyInternationalRelations(name) {
  const bare = name.startsWith(TICK) ? name.slice(TICK.length) : name;
  if (OVERRIDES[bare]) return { dest: OVERRIDES[bare], note: 'override' };
  for (const re of IR_KEEP_RE) if (re.test(bare)) return { keep: true, note: 'genuine IR (re)' };
  for (const r of IR_RULES) if (r.re.test(bare)) return r;
  for (const r of FISH_RULES) if (r.re.test(bare)) return r;
  for (const re of IR_PERSON_RE) if (re.test(bare)) return { dest: 'Personalities', note: 'person-like' };
  return { dest: IR_AUTO.dest, note: 'auto-assign fallback' };
}

function classify(name) {
  const bare = name.startsWith(TICK) ? name.slice(TICK.length) : name;
  if (OVERRIDES[bare]) return { dest: OVERRIDES[bare], note: 'override' };
  for (const r of RULES) if (r.re.test(bare)) return r;
  return null;
}

function loadFiles() {
  const files = [];
  let i = 0;
  while (true) {
    const slug = SOURCE + (i === 0 ? '' : '-' + (i + 1));
    if (fs.existsSync(path.join(DIR, slug + '.json'))) { files.push(slug); i++; }
    else break;
  }
  return files;
}

function slugFor(cat) {
  return cat.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function loadCategory(slug) {
  const p = path.join(DIR, slug + '.json');
  if (!fs.existsSync(p)) return { file: p, data: null };
  return { file: p, data: JSON.parse(fs.readFileSync(p, 'utf8')) };
}

function writeCategory(file, data) {
  fs.writeFileSync(file, JSON.stringify(data));
}

// Move every planned sub-topic out of the source category into its destination,
// renaming the destination sub-topic with the TICK prefix and rewriting each
// question's category/subject/subSubject so archive rebuilds keep the move.
function apply(files, plan) {
  const sources = files.map(f => {
    const p = path.join(DIR, f + '.json');
    return { file: p, data: JSON.parse(fs.readFileSync(p, 'utf8')) };
  });
  const targets = {}; // dest name -> { file, data }

  const dests = Object.keys(plan).sort();
  let totalQ = 0;
  dests.forEach(dest => {
    const names = plan[dest].names;
    names.forEach(name => {
      // locate source sub-topic across the source part files
      let found = null;
      for (const s of sources) {
        const subj = Object.keys(s.data)[0];
        const subs = s.data[subj].subSubjects;
        if (subs[name] !== undefined) { found = { s, subj, subs, qs: subs[name] }; break; }
      }
      if (!found) { console.log('  !! not found in source: ' + name); return; }

      const t = targets[dest] || (targets[dest] = loadOrCreate(dest));
      const tSubj = Object.keys(t.data)[0];
      const tSubs = t.data[tSubj].subSubjects;

      const tickName = TICK + name;
      found.qs.forEach(q => {
        q.category = dest;
        q.subject = dest;
        q.subSubject = tickName;
      });
      if (!tSubs[tickName]) tSubs[tickName] = [];
      tSubs[tickName] = tSubs[tickName].concat(found.qs);

      delete found.subs[name];
      totalQ += found.qs.length;
    });
    console.log('  ' + dest + ': +' + names.length + ' sub-topics');
  });

  sources.forEach(s => writeCategory(s.file, s.data));
  Object.keys(targets).forEach(dest => writeCategory(targets[dest].file, targets[dest].data));

  // safety: no source part may be left empty of subSubjects
  sources.forEach(s => {
    const subj = Object.keys(s.data)[0];
    if (!s.data[subj].subSubjects || Object.keys(s.data[subj].subSubjects).length === 0) {
      console.log('  WARN: ' + path.basename(s.file) + ' now empty of sub-topics ΓÇö untouched.');
    }
  });

  console.log('APPLIED: ' + dests.length + ' destinations, ' + totalQ + ' questions moved.');
}

function loadOrCreate(cat) {
  const slug = slugFor(cat);
  const existing = loadCategory(slug);
  if (existing.data) return existing;
  const data = {};
  data[cat] = { subSubjects: {} };
  return { file: existing.file, data };
}

function main() {
  const files = loadFiles();
  const src = {}; // name -> qLeft
  files.forEach(f => {
    const d = JSON.parse(fs.readFileSync(path.join(DIR, f + '.json'), 'utf8'));
    const subj = Object.keys(d)[0];
    const ss = d[subj].subSubjects;
    Object.entries(ss).forEach(([k, qs]) => {
      if (!src[k]) src[k] = 0;
      src[k] += (Array.isArray(qs) ? qs.length : 0);
    });
  });
  const srcDisplay = files.length ? Object.keys(JSON.parse(fs.readFileSync(path.join(DIR, files[0] + '.json'), 'utf8')))[0] : SOURCE;
  const junkMode = JUNK_SOURCES.has(srcDisplay);
  const fishMode = srcDisplay === 'Aquaculture' || srcDisplay === 'Fisheries & Aquaculture';
  const irMode = srcDisplay === 'International Relations';

  const plan = {};
  const stars = [];
  const unclassified = [];
  const keys = Object.keys(src).sort((a, b) => a.localeCompare(b, 'en'));
  keys.forEach(k => {
    const bare = k.startsWith(TICK) ? k.slice(TICK.length) : k;
    // Already moved-in (TICK prefix) ΓåÆ leave untouched (never double-move)
    if (k.startsWith(TICK)) { stars.push(k); return; }
    if (STARS.has(k) || STARS.has(bare)) { stars.push(k); return; }
    if (fishMode) {
      const fr = classifyFisheries(k);
      if (fr.keep || (fr.dest && fr.dest === srcDisplay)) { stars.push(k); return; }
      if (!plan[fr.dest]) plan[fr.dest] = { note: fr.note, names: [] };
      plan[fr.dest].names.push(k);
      return;
    }
    if (irMode) {
      const rr = classifyInternationalRelations(k);
      if (rr.keep || (rr.dest && rr.dest === srcDisplay)) { stars.push(k); return; }
      if (!plan[rr.dest]) plan[rr.dest] = { note: rr.note, names: [] };
      plan[rr.dest].names.push(k);
      return;
    }
    const r = classify(k);
    // destination == source is a keep, not a move
    if (r && r.dest === srcDisplay) { stars.push(k); return; }
    if (junkMode) {
      // keep by default; move only clear junk. OVERRIDES is high-precision
      // (explicitly curated), RULES/JUNK_RULES only when they match.
      if (OVERRIDES[bare]) { if (!plan[OVERRIDES[bare]]) plan[OVERRIDES[bare]] = { note: 'override', names: [] }; plan[OVERRIDES[bare]].names.push(k); return; }
      for (const jr of JUNK_RULES) {
        if (jr.except && jr.except.includes(srcDisplay)) continue;
        if (jr.re.test(bare)) {
          if (jr.dest === srcDisplay) { stars.push(k); return; }
          if (!plan[jr.dest]) plan[jr.dest] = { note: jr.note, names: [] };
          plan[jr.dest].names.push(k);
          return;
        }
      }
      // Not clearly junk ΓåÆ keep (count as genuine)
      stars.push(k);
      return;
    }
    if (r) { if (!plan[r.dest]) plan[r.dest] = { note: r.note, names: [] }; plan[r.dest].names.push(k); }
    else unclassified.push(k);
  });

  if (MODE === 'apply') {
    apply(files, plan);
    return;
  }

  const totQ = keys.reduce((s, k) => s + src[k], 0);
  console.log('\n===== ' + SOURCE + ' =====  ' + keys.length + ' sub-topics / ' + totQ + ' q');
  console.log('\nΓÿà KEEP in ' + SOURCE + ' (genuine): ' + stars.length + ' sub-topics / ' + stars.reduce((s, k) => s + src[k], 0) + ' q');
  stars.forEach(k => console.log('   Γÿà ' + k));
  Object.keys(plan).sort().forEach(dest => {
    const p = plan[dest];
    console.log('\nMOVE ΓåÆ ' + dest + ' (' + p.names.length + ' sub-topics / ' + p.names.reduce((s, k) => s + src[k], 0) + ' q):');
    p.names.forEach(k => console.log('   ┬╖ ' + k));
  });
  console.log('\nUNCLASSIFIED (needs manual review, ' + unclassified.length + ' / ' + unclassified.reduce((s, k) => s + src[k], 0) + ' q):');
  unclassified.forEach(k => console.log('   ? ' + k));
  fs.writeFileSync(path.join(ROOT, 'scripts', '_' + SOURCE + '_plan.json'),
    JSON.stringify({ files, keys, src, stars, plan: Object.fromEntries(Object.entries(plan).map(([d, p]) => [d, p.names])), unclassified }, null, 1));
}



